def main() -> None:
    src = {json.loads(x)["qid"]: json.loads(x) for x in (ROOT / "data/v4/rset/r_queries.draft.jsonl").open(encoding="utf-8")}
    out = ROOT / "data/v4/rset/r_gold.jsonl"
    with out.open("w", encoding="utf-8") as f:
        for g in GOLD:
            row = {k: v for k, v in src[g["qid"]].items() if k != "ref"} | {"ref": {k: v for k, v in g.items() if k != "qid"}}
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(len(GOLD), "labels ->", out)


if __name__ == "__main__":
    main()
