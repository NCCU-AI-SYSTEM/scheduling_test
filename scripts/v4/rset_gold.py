"""Gold labels for the R-set (realistic forum-style queries), annotated by hand.

Annotated by Claude (Opus 5.5) on 2026/10/18 after the gpt-oss:120b draft proved
unreliable (missed weekday/afternoon/credits in compound queries, no exclusions for
不要早上). Annotator's model family differs from both systems under test (Gemma, Qwen).

Conventions
  need          topic only; empty when the query has no topic
  conditions    only what can be checked in the DB: weekday, hour_range, course_lang,
                point, kind (必修/選修/群修/通識/體育), lmt_kind, unit. "外系能修" is an
                eligibility question, not a unit condition.
  prefs         "aspect+" wants high, "aspect-" wants low. 涼 -> workload-, 甜 -> grading+,
                不要太硬 -> difficulty-, 不點名 -> attendance-, 不分組 -> group_work-,
                實用 -> usefulness+, 期末不用考試 / 只交報告 -> workload-
  intents       search, lookup, review, eligibility, enroll_chance, compare,
                out_of_scope (needs earlier context such as 這門, or not about this
                semester's courses), unsupported (answerable only with data we do not
                have: grade distributions, Pass/Fail, textbook purchase, presentation counts)

  python -m scripts.v4.rset_gold        writes data/v4/rset/r_gold.jsonl
"""

