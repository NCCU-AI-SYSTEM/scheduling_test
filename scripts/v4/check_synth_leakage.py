"""How much of a synthetic query's wording is already in the gold course's LLM meta?

eval_synth queries and course_meta_v1 summaries/keywords were both generated by
LLMs (gpt-4o-mini for most of each). If queries share bigrams with the meta far
more than with the course's own name+objective, BM25 gains from adding meta
(D-V2) partly measure generator overlap, not retrieval quality.
"""

from __future__ import annotations

import collections
import json
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STOP = "想學想找有沒有的課程課啊嗎呢那種相關一些可以什麼"


def bigrams(t: str) -> set[str]:
    t = re.sub(r"[^一-鿿]", "", t)
    return {t[i:i + 2] for i in range(len(t) - 1)}


def main() -> None:
    stop = bigrams(STOP)
    meta = {}
    for cid, summ, kw, tags, model in sqlite3.connect(ROOT / "data/processed/course_meta.db").execute(
            "SELECT course_id, summary_100, keywords_json, topic_tags_json, model FROM course_meta_v1"):
        text = (summ or "") + json.dumps(json.loads(kw or "[]"), ensure_ascii=False) + json.dumps(json.loads(tags or "[]"), ensure_ascii=False)
        meta[cid] = (bigrams(text), model)
    own = {}
    for cid, name, obj in sqlite3.connect(ROOT / "data/1142.db").execute(
            "SELECT substr(id,1,13), name, objective FROM COURSE WHERE y='114' AND s='2'"):
        own[cid] = bigrams((name or "") + (obj or ""))
    acc = collections.defaultdict(lambda: [0, 0.0, 0.0])
    for line in (ROOT / "data/raw/eval_synth_clean.jsonl").open(encoding="utf-8"):
        r = json.loads(line)
        g = r["gold_course_id"]
        q = bigrams(r["query"]) - stop
        if r["type"] == "constraint" or not q or g not in meta:
            continue
        m, model = meta[g]
        a = acc[model]
        a[0] += 1
        a[1] += len(q & m) / len(q)
        a[2] += len(q & own.get(g, set())) / len(q)
    for model, (n, m, o) in acc.items():
        print(f"{model:24s} n={n:5d}  query bigrams in LLM meta {m / n:.3f}  in name+objective {o / n:.3f}")


if __name__ == "__main__":
    main()
